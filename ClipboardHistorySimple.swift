/// Captures the NSWindow hosting a SwiftUI view so an NSOpenPanel can be attached to it as a sheet.
struct SettingsWindowReader: NSViewRepresentable {
    let onWindowAvailable: (NSWindow?) -> Void

    func makeNSView(context: Context) -> NSView {
        let view = WindowReportingView()
        view.onWindowAvailable = onWindowAvailable
        return view
    }

    func updateNSView(_ nsView: NSView, context: Context) {}

    /// Reports its window from viewDidMoveToWindow, once per window identity.
    final class WindowReportingView: NSView {
        var onWindowAvailable: ((NSWindow?) -> Void)?
        private weak var reportedWindow: NSWindow?

        override func viewDidMoveToWindow() {
            super.viewDidMoveToWindow()
            guard window !== reportedWindow else { return }
            reportedWindow = window
            DispatchQueue.main.async { [weak self] in
                self?.onWindowAvailable?(self?.window)
            }
        }
    }
}

