        guard let settingsWindow else { return }
        let panel = NSOpenPanel()
        panel.allowedContentTypes = [.application]
        panel.directoryURL = URL(fileURLWithPath: "/Applications")
        panel.allowsMultipleSelection = true
        panel.canChooseDirectories = false
        panel.prompt = "Ignore"
        panel.beginSheetModal(for: settingsWindow) { response in
            guard response == .OK else { return }
            var addedAny = false
            for url in panel.urls {
                // Apps without a bundle ID can't be matched, so they are skipped.
                guard let bundleID = Bundle(url: url)?.bundleIdentifier else { continue }
                if manager.addIgnoredApp(bundleID: bundleID) { addedAny = true }
            }
            if addedAny { showPurgeConfirmation = true }
        }
    }
