// MARK: - Clipboard Item Model
struct ClipboardItem: Identifiable, Codable {
    let id: UUID
    let content: String
    let timestamp: Date
    let sourceBundleID: String?

    init(content: String, timestamp: Date, sourceBundleID: String? = nil) {
        self.id = UUID()
        self.content = content
        self.timestamp = timestamp
        self.sourceBundleID = sourceBundleID
    }

    init(id: UUID, content: String, timestamp: Date, sourceBundleID: String?) {
        self.id = id
        self.content = content
        self.timestamp = timestamp
        self.sourceBundleID = sourceBundleID
    }

    var displayText: String {
        String(content.prefix(100))
    }

    var timeAgo: String {
        let formatter = RelativeDateTimeFormatter()
        formatter.unitsStyle = .abbreviated
        return formatter.localizedString(for: timestamp, relativeTo: Date())
    }
}

// MARK: - Privacy
enum Privacy {
    static let ignoredAppsDefaultsKey = "ignoredAppBundleIDs"

    /// Pasteboard types that mark a copy as a password, one-time code or other secret.
    /// Contents carrying any of them are never saved.
    static let secretMarkerPasteboardTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
        NSPasteboard.PasteboardType("com.typeit4me.clipping"),
        NSPasteboard.PasteboardType("Pasteboard generator type")
    ]

    /// Optional marker whose value is the bundle ID of the app that wrote the pasteboard.
    static let sourceAppPasteboardType = NSPasteboard.PasteboardType("org.nspasteboard.source")

    static let defaultIgnoredBundleIDs: [String] = [
        "com.apple.Passwords",
        "com.apple.keychainaccess",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc"
    ]
}

// MARK: - Persistence
struct PersistenceManager {
    private static var storageURL: URL {
        let appSupport = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first!
        let appDir = appSupport.appendingPathComponent("ClipboardHistory")
        if !FileManager.default.fileExists(atPath: appDir.path) {
            try? FileManager.default.createDirectory(at: appDir, withIntermediateDirectories: true)
        }
        return appDir.appendingPathComponent("history.json")
    }

    static func save(_ items: [ClipboardItem]) {
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        guard let data = try? encoder.encode(items) else { return }
        try? data.write(to: storageURL, options: .atomic)
    }

    static func load() -> [ClipboardItem] {
        guard let data = try? Data(contentsOf: storageURL) else { return [] }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        return (try? decoder.decode([ClipboardItem].self, from: data)) ?? []
    }
}

// MARK: - Clipboard Manager
class ClipboardManager: ObservableObject {
    @Published var items: [ClipboardItem] = []
    @Published var historyLimit: Int {
        didSet { UserDefaults.standard.set(historyLimit, forKey: "historyLimit") }
    }
    @Published var ignoredAppBundleIDs: [String] {
        didSet { UserDefaults.standard.set(ignoredAppBundleIDs, forKey: Privacy.ignoredAppsDefaultsKey) }
    }
    private var timer: Timer?
    private var lastChangeCount = 0
    private var frontmostBundleIDAtLastPoll: String?
    private var bundleIDsActivatedSinceLastPoll = Set<String>()
    private var activationObserver: NSObjectProtocol?

    init() {
        let saved = UserDefaults.standard.integer(forKey: "historyLimit")
        self.historyLimit = saved > 0 ? saved : 50
        if UserDefaults.standard.object(forKey: Privacy.ignoredAppsDefaultsKey) == nil {
            self.ignoredAppBundleIDs = Privacy.defaultIgnoredBundleIDs
        } else {
            self.ignoredAppBundleIDs = UserDefaults.standard.stringArray(forKey: Privacy.ignoredAppsDefaultsKey) ?? []
        }
        self.items = PersistenceManager.load()
    }

    func startMonitoring() {
        lastChangeCount = NSPasteboard.general.changeCount
        frontmostBundleIDAtLastPoll = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        activationObserver = NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification,
            object: nil,
            queue: .main
        ) { [weak self] notification in
            let activatedApp = notification.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication
            if let bundleID = activatedApp?.bundleIdentifier {
                self?.bundleIDsActivatedSinceLastPoll.insert(bundleID)
            }
        }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
            self.checkClipboard()
        }
    }

    private func checkClipboard() {
        let pasteboard = NSPasteboard.general
        let changeCount = pasteboard.changeCount
        let currentFrontmostBundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier

        defer {
            frontmostBundleIDAtLastPoll = currentFrontmostBundleID
            bundleIDsActivatedSinceLastPoll.removeAll()
        }

        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        // Check privacy markers before reading any content.
        let pasteboardTypes = pasteboard.types ?? []
        guard !pasteboardTypes.contains(where: { Privacy.secretMarkerPasteboardTypes.contains($0) }) else { return }

        let sourceBundleID: String?
        if pasteboardTypes.contains(Privacy.sourceAppPasteboardType) {
            // The declared source is authoritative; an empty value means unknown (never the frontmost app).
            let declaredSource = pasteboard.string(forType: Privacy.sourceAppPasteboardType) ?? ""
            sourceBundleID = declaredSource.isEmpty ? nil : declaredSource
            if let sourceBundleID, ignoredAppBundleIDs.contains(sourceBundleID) { return }
        } else {
            // Best-effort fallback: the copy may have come from any app that was frontmost
            // or activated since the last poll.
            var candidateBundleIDs = bundleIDsActivatedSinceLastPoll
            if let previous = frontmostBundleIDAtLastPoll { candidateBundleIDs.insert(previous) }
            if let current = currentFrontmostBundleID { candidateBundleIDs.insert(current) }
            if !candidateBundleIDs.isDisjoint(with: ignoredAppBundleIDs) { return }
            sourceBundleID = currentFrontmostBundleID
        }

        if let string = pasteboard.string(forType: .string), !string.isEmpty {
            let item = ClipboardItem(content: string, timestamp: Date(), sourceBundleID: sourceBundleID)
            DispatchQueue.main.async {
                self.items.removeAll { $0.content == item.content }
                self.items.insert(item, at: 0)
                if self.items.count > self.historyLimit {
                    self.items = Array(self.items.prefix(self.historyLimit))
                }
                PersistenceManager.save(self.items)
            }
        }
    }

    func copyItem(_ item: ClipboardItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(item.content, forType: .string)
        lastChangeCount = pasteboard.changeCount

        // Move the copied item to the top with a fresh timestamp, keeping its id and source.
        let promotedItem = ClipboardItem(id: item.id, content: item.content, timestamp: Date(), sourceBundleID: item.sourceBundleID)
        items.removeAll { $0.id == item.id }
        items.insert(promotedItem, at: 0)
        PersistenceManager.save(items)
    }

    func deleteItem(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        PersistenceManager.save(items)
    }

    func clearAll() {
        items.removeAll()
        PersistenceManager.save(items)
    }

    // MARK: Ignored apps

    /// Returns true when the list actually gained the bundle ID.
    @discardableResult
    func addIgnoredApp(bundleID: String) -> Bool {
        guard !ignoredAppBundleIDs.contains(bundleID) else { return false }
        ignoredAppBundleIDs.append(bundleID)
        return true
    }

    func removeIgnoredApp(bundleID: String) {
        ignoredAppBundleIDs.removeAll { $0 == bundleID }
    }

    /// Returns true when the list gained at least one bundle ID.
    @discardableResult
    func restoreDefaultIgnoredApps() -> Bool {
        let previousBundleIDs = Set(ignoredAppBundleIDs)
        ignoredAppBundleIDs = Privacy.defaultIgnoredBundleIDs
        return !Set(Privacy.defaultIgnoredBundleIDs).isSubset(of: previousBundleIDs)
    }

    var itemsFromIgnoredAppsCount: Int {
        items.filter { item in
            guard let sourceBundleID = item.sourceBundleID else { return false }
            return ignoredAppBundleIDs.contains(sourceBundleID)
        }.count
    }

    func deleteItemsFromIgnoredApps() {
        items.removeAll { item in
            guard let sourceBundleID = item.sourceBundleID else { return false }
            return ignoredAppBundleIDs.contains(sourceBundleID)
        }
        PersistenceManager.save(items)
    }
}

// MARK: - Hotkey
struct Hotkey: Equatable {
    var keyCode: UInt32
    var modifiers: UInt32  // Carbon modifier mask (cmdKey, shiftKey, optionKey, controlKey)
    var keyLabel: String

    static let defaultHotkey = Hotkey(
        keyCode: UInt32(kVK_ANSI_V),
        modifiers: UInt32(cmdKey | shiftKey),
        keyLabel: "V"
    )

    var displayString: String {
        var result = ""
        if modifiers & UInt32(controlKey) != 0 { result += "⌃" }
        if modifiers & UInt32(optionKey) != 0 { result += "⌥" }
        if modifiers & UInt32(shiftKey) != 0 { result += "⇧" }
        if modifiers & UInt32(cmdKey) != 0 { result += "⌘" }
        return result + keyLabel
    }

    static func carbonModifiers(from flags: NSEvent.ModifierFlags) -> UInt32 {
        var mask: UInt32 = 0
        if flags.contains(.command) { mask |= UInt32(cmdKey) }
        if flags.contains(.shift) { mask |= UInt32(shiftKey) }
        if flags.contains(.option) { mask |= UInt32(optionKey) }
        if flags.contains(.control) { mask |= UInt32(controlKey) }
        return mask
    }
}

final class HotkeyManager: ObservableObject {
    static let shared = HotkeyManager()

    private static let keyCodeDefaultsKey = "hotkeyKeyCode"
    private static let modifiersDefaultsKey = "hotkeyModifiers"
    private static let keyLabelDefaultsKey = "hotkeyKeyLabel"
    private static let hotkeySignature: OSType = 0x434C4248  // "CLBH"
    private static let hotkeyIdentifier: UInt32 = 1

    @Published private(set) var currentHotkey: Hotkey
    @Published var lastErrorMessage: String?

    var onHotkeyPressed: (() -> Void)?

    private var hotKeyRef: EventHotKeyRef?
    private var eventHandlerRef: EventHandlerRef?

    private init() {
        currentHotkey = HotkeyManager.loadPersistedHotkey()
    }

    private static func loadPersistedHotkey() -> Hotkey {
        let defaults = UserDefaults.standard
        guard defaults.object(forKey: keyCodeDefaultsKey) != nil,
              defaults.object(forKey: modifiersDefaultsKey) != nil,
              let keyCode = UInt32(exactly: defaults.integer(forKey: keyCodeDefaultsKey)),
              let modifiers = UInt32(exactly: defaults.integer(forKey: modifiersDefaultsKey)),
              modifiers & UInt32(cmdKey | controlKey | optionKey) != 0,
              let label = defaults.string(forKey: keyLabelDefaultsKey),
              !label.isEmpty else {
            return Hotkey.defaultHotkey
        }
        return Hotkey(keyCode: keyCode, modifiers: modifiers, keyLabel: label)
    }

    private func persist(_ hotkey: Hotkey) {
        let defaults = UserDefaults.standard
        defaults.set(Int(hotkey.keyCode), forKey: HotkeyManager.keyCodeDefaultsKey)
        defaults.set(Int(hotkey.modifiers), forKey: HotkeyManager.modifiersDefaultsKey)
        defaults.set(hotkey.keyLabel, forKey: HotkeyManager.keyLabelDefaultsKey)
    }

    /// Installs the application-level handler for hotkey presses. Call once.
    @discardableResult
    func installEventHandler() -> Bool {
        guard eventHandlerRef == nil else { return true }

        var eventType = EventTypeSpec(
            eventClass: OSType(kEventClassKeyboard),
            eventKind: UInt32(kEventHotKeyPressed)
        )
        let userData = Unmanaged.passUnretained(self).toOpaque()

        let status = InstallEventHandler(
            GetApplicationEventTarget(),
            { _, event, userData in
                guard let event = event, let userData = userData else {
                    return OSStatus(eventNotHandledErr)
                }
                var pressedHotKeyID = EventHotKeyID()
                let parameterStatus = GetEventParameter(
                    event,
                    EventParamName(kEventParamDirectObject),
                    EventParamType(typeEventHotKeyID),
                    nil,
                    MemoryLayout<EventHotKeyID>.size,
                    nil,
                    &pressedHotKeyID
                )
                guard parameterStatus == noErr,
                      pressedHotKeyID.signature == HotkeyManager.hotkeySignature,
                      pressedHotKeyID.id == HotkeyManager.hotkeyIdentifier else {
                    return OSStatus(eventNotHandledErr)
                }
                let manager = Unmanaged<HotkeyManager>.fromOpaque(userData).takeUnretainedValue()
                DispatchQueue.main.async {
                    manager.onHotkeyPressed?()
                }
                return noErr
            },
            1,
            &eventType,
            userData,
            &eventHandlerRef
        )
        if status != noErr {
            NSLog("ClipboardHistory: could not install hotkey event handler (status \(status))")
            lastErrorMessage = "Couldn't enable the keyboard shortcut."
            return false
        }
        return true
    }

    private func unregisterHotkey() {
        if let ref = hotKeyRef {
            UnregisterEventHotKey(ref)
            hotKeyRef = nil
        }
    }

    /// Unregisters any existing hotkey and registers `hotkey` exclusively.
    private func register(_ hotkey: Hotkey) -> OSStatus {
        unregisterHotkey()
        let hotKeyID = EventHotKeyID(
            signature: HotkeyManager.hotkeySignature,
            id: HotkeyManager.hotkeyIdentifier
        )
        var newRef: EventHotKeyRef?
        let status = RegisterEventHotKey(
            hotkey.keyCode,
            hotkey.modifiers,
            hotKeyID,
            GetApplicationEventTarget(),
            OptionBits(kEventHotKeyExclusive),
            &newRef
        )
        if status == noErr {
            hotKeyRef = newRef
        }
        return status
    }

    func registerCurrentHotkey() {
        guard installEventHandler() else {
            lastErrorMessage = "Couldn't enable the keyboard shortcut."
            return
        }
        let status = register(currentHotkey)
        if status != noErr {
            NSLog("ClipboardHistory: could not register hotkey \(currentHotkey.displayString) (status \(status))")
            lastErrorMessage = "Couldn't register \(currentHotkey.displayString) (it may be in use)."
        } else {
            lastErrorMessage = nil
        }
    }

    /// Temporarily unregisters the hotkey, e.g. while the user records a new one.
    func suspend() {
        unregisterHotkey()
    }

    func resume() {
        registerCurrentHotkey()
    }

    @discardableResult
    func apply(_ newHotkey: Hotkey) -> Bool {
        guard installEventHandler() else {
            lastErrorMessage = "Couldn't enable the keyboard shortcut."
            return false
        }
        let status = register(newHotkey)
        if status == noErr {
            currentHotkey = newHotkey
            persist(newHotkey)
            lastErrorMessage = nil
            return true
        }

        NSLog("ClipboardHistory: could not register hotkey \(newHotkey.displayString) (status \(status))")
        if register(currentHotkey) == noErr {
            lastErrorMessage = "Couldn't register \(newHotkey.displayString) (it may be in use). Kept \(currentHotkey.displayString)."
        } else {
            lastErrorMessage = "Couldn't register any shortcut."
        }
        return false
    }

    func resetToDefault() {
        apply(Hotkey.defaultHotkey)
    }
}

